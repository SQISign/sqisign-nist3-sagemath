import crypto.utils as utils
from ec.ec_curve import ECCurve
from ec.ec_point import ECPoint

class ECIsogeny:
    r"""
    Implements the type ECIsog [Definition 4.4.2].

    The isogeny of degree `2^e` with kernel `\langle [4]K \rangle`, computed as
    a chain of 4-isogenies.

    INPUT:

    - ``E`` -- the domain :class:`ECCurve`
    - ``K`` -- a point of order `2^{e+2}` on ``E``
    - ``e`` -- an even positive integer
    """

    def __init__(self, E, K, e):
        if not isinstance(E, ECCurve):
            raise TypeError("The input curve is not a Montgomery curve")

        if not isinstance(K, ECPoint):
            raise TypeError("The kernel generator not defined over a Montgomery curve")

        if e % 2 != 0:
            raise ValueError("e must be even, 2-isogenies are not implemented")

        self._domain = E
        self._kernel = K
        self._degree = e+2
        self._codomain = None

    def _ec_four_isogeny_codomain(self, xP, zP):
        r"""
        [Algorithm 4.97] FourIsogenyCodomain, on coordinates.
        """
        c0 = zP**2
        c1 = xP - zP
        c2 = xP + zP
        t0 = xP**2
        t3 = c0 + t0
        t4 = c0 - t0
        A24 = t3 * t4
        C24 = c0**2
        c0 = c0 + c0
        c0 = c0 + c0

        return A24, C24, [c0, c1, c2]

    def ec_four_isogeny_codomain(self):
        r"""
        [Algorithm 4.97] FourIsogenyCodomain.

        Compute the codomain of the 4-isogeny with kernel generated by the kernel
        point, which must have order 4.

        OUTPUT:

        A tuple ``(E, consts)`` with ``E`` the codomain and ``consts`` the
        constants for :meth:`ec_four_isogeny_eval`.
        """

        xP = self._kernel._x
        zP = self._kernel._z

        A24, C24, consts = self._ec_four_isogeny_codomain(xP, zP)

        A = A24 + A24
        A = A - C24
        A = A + A
        C = C24**-1
        A = A * C

        E = ECCurve(A)
        self._codomain = E

        return E, consts

    def _ec_four_isogeny_eval(self, xQ, zQ, consts):
        r"""
        [Algorithm 4.98] FourIsogenyEval, on coordinates.
        """
        c0, c1, c2 = consts
        t0 = xQ + zQ
        t1 = xQ - zQ
        xQ = t0 * c1
        zQ = t1 * c2
        t0 = t0 * t1
        t0 = t0 * c0
        t1 = xQ + zQ
        zQ = xQ - zQ
        t1 = t1**2
        zQ = zQ**2
        xQ = t0 + t1
        t0 = t0 - zQ
        xQ = xQ * t1
        zQ = zQ * t0

        return xQ, zQ

    def ec_four_isogeny_eval(self, Q, consts):
        r"""
        [Algorithm 4.98] FourIsogenyEval.

        INPUT:

        - ``Q`` -- a point on the domain
        - ``consts`` -- the constants from :meth:`ec_four_isogeny_codomain`

        OUTPUT:

        The image of ``Q``.
        """

        xQ, zQ = Q.xz()

        xQ, zQ = self._ec_four_isogeny_eval(xQ, zQ, consts)

        return self._codomain([xQ, zQ])


    def ec_two_isogeny_chain(self, pts):
        r"""
        [Algorithm 4.99] TwoIsogenyChain.

        Evaluate the isogeny and normalize the codomain as in [Algorithm 4.96]
        NormalizeMontgomery.

        INPUT:

        - ``pts`` -- a list of points on the domain

        OUTPUT:

        A tuple ``(E, image_pts)`` with ``E`` the normalized codomain and
        ``image_pts`` the images of ``pts``.
        """

        e = self._degree
        P = self._kernel
        E = self._domain

        Fp2 = P._parent._Fp2
        zero = Fp2(0)
        i_Fp2 = Fp2.gen()

        strat_pts = [P]
        orders = [e]
        k = 0

        for j in range(0, e // 2 - 1):
            while orders[k] != 2:
                k += 1
                n = (orders[k - 1] // 4) * 2 + (orders[k - 1] % 2)
                orders.append(orders[k - 1] - n)
                strat_pts.append(strat_pts[k - 1])

                for i in range(0, n):
                    strat_pts[k] = strat_pts[k].ec_dbl()

            K = strat_pts.pop()
            _ = orders.pop()

            if j == 0:
                twoK = K.ec_dbl()
                fourK = twoK.ec_dbl()
                if twoK._z == zero or fourK._z != zero:
                    raise ValueError("TwoIsogenyChain failed: wrong point order")
                if twoK._x == zero:
                    raise ValueError("TwoIsogenyChain failed: unexpected singular 4-isogeny")

            phi = ECIsogeny(E, K, 2)
            E, consts = phi.ec_four_isogeny_codomain()

            strat_pts = [phi.ec_four_isogeny_eval(Q, consts) for Q in strat_pts]

            orders = [m - 2 for m in orders]

            k -= 1

            pts = [phi.ec_four_isogeny_eval(Q, consts) for Q in pts]


        K = strat_pts[0]
        X, Z = K._x, K._z

        A1 = 2 * (X**4 + Z**4) / (X**4 - Z**4)

        X2, Z2 = X + Z, X - Z
        A2 = 2 * (X2**4 + Z2**4) / (X2**4 - Z2**4)

        X3, Z3 = i_Fp2 * X + Z, X + i_Fp2 * Z
        A3 = 2 * (X3**4 + Z3**4) / (X3**4 - Z3**4)

        A_candidates = [A1, A2, A3, -A1, -A2, -A3]

        A_normalized = A_candidates[0]

        for A in A_candidates[1:]:
            if utils.fp2_compare(A_normalized, A):
                A_normalized = A

        E = ECCurve(A_normalized)
        self._codomain = E

        return E, pts
